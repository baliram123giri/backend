const reverseMap = {};

[JAIN_GOTRA_TRANSLATIONS, VEDIC_GOTRA_TRANSLATIONS].forEach((collection) => {
  Object.keys(collection).forEach((lang) => {
    const dict = collection[lang];
    Object.keys(dict).forEach((canonicalKey) => {
      const val = dict[canonicalKey];
      if (val) {
        reverseMap[val.trim()] = canonicalKey;
        reverseMap[val.trim().toLowerCase()] = canonicalKey;
      }
      reverseMap[canonicalKey.trim()] = canonicalKey;
      reverseMap[canonicalKey.trim().toLowerCase()] = canonicalKey;
    });
  });
});

export function getCanonicalGotraKey(value) {
  if (!value) return undefined;
  const trimmed = value.trim();
  return reverseMap[trimmed] || reverseMap[trimmed.toLowerCase()];
}
